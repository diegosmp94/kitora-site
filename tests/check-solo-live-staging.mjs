import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(p,"utf8");
const checkout=read("supabase/functions/create-checkout-live/index.ts");
const webhook=read("supabase/functions/stripe-webhook-live/index.ts");
const db=read("security/kitora-live-solo-subscription.sql");
const cart=read("cart.js"), catalog=read("packs-actifs.html"), account=read("compte.html");
const price="price_1USLrS0xrx52eQIkfvGoRzqK";
assert.ok(checkout.includes('solo:"'+price+'"'),"LIVE Solo price must be pinned");
assert.ok(webhook.includes('solo:"'+price+'"'),"LIVE Solo webhook price must match checkout");
assert.match(checkout,/KITORA_LIVE_CHECKOUT_ENABLED/,"Kill switch missing");
assert.match(checkout,/KITORA_LIVE_SOLO_ENABLED/,"Independent Solo launch kill switch missing");
assert.match(checkout,/price\.unit_amount!==199/,"LIVE checkout must verify exactly EUR 1.99");
assert.match(checkout,/price\.currency!=="eur"/);
assert.match(checkout,/price\.recurring\?\.interval!=="month"/);
assert.match(checkout,/Object\.prototype\.hasOwnProperty\.call\(prices,b\.plan\)/,"Reject unknown client supplied tiers");
assert.doesNotMatch(checkout,/const prices:[^\n]+plus_monthly/,"Only Solo may be in launched offer list");
assert.match(webhook,/constructEventAsync/,"Unsigned webhook may not change entitlement");
assert.match(webhook,/kitora_commit_live_stripe_event_safe/,"Must retain atomic event deduplication");
assert.match(webhook,/if\(!event\.livemode\)/,"Must reject TEST events");
assert.match(db,/ADD CONSTRAINT kitora_live_subscriptions_plan_check/,"LIVE Solo table constraint required");
assert.match(db,/new_clause text := 'p_plan not in/,"RPC must accept Solo");
assert.match(db,/Unexpected webhook RPC definition; abort/,"No unsafe blind migration");
assert.doesNotMatch(cart,/create-checkout-live/,"Public cart must not initiate LIVE purchases yet");
assert.match(catalog,/data-pack-id="solo" data-pack-status="launch-pending"/,"Live selling may not be advertised before compliance approval");
assert.match(account,/customer-portal-live/,"LIVE cancellation route required");
console.log("Kitora Solo LIVE staging: pricing, launch flags, signed webhook, isolated price mapping, DB readiness and prelaunch UI PASS.");
